"""Write the self-hosting contract into every file an AI tool reads, in every Ultrastable repository.

One contract (agents/CONTRACT.md), many doors: AGENTS.md (the open convention read by Codex, Copilot, Cursor, Jules and
others), CLAUDE.md, GEMINI.md, .github/copilot-instructions.md, .cursor/rules/ultrastable.mdc, plus the pull request and
issue templates that carry the record the contract asks for.

  python tools/sync_agent_files.py --repo workers --target .            # write
  python tools/sync_agent_files.py --repo spec --target ../ultrastable-spec
  python tools/sync_agent_files.py --repo workers --target . --check    # exit 1 if any file differs (CI)
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
HDR = "<!-- SPDX-License-Identifier: LicenseRef-Ultrastable-USL-1.0 -->\n<!-- Copyright (c) 2026 Rowan Brad Quni-Gudzinas -->\n<!-- Generated by tools/sync_agent_files.py from agents/CONTRACT.md. Edit the contract in ultrastable/workers, not this file. -->\n"

REPOS = {
    "workers": {
        "what": "The code: Cloudflare Worker core, console, bootstrapper, adapters, core modules, setup skill.",
        "test": "`npm test` (JavaScript and Python suites; includes the separation guard `core/test/no-qnfo.test.js`).",
        "rules": [
            "No tenant names, hosts or account ids anywhere in code or configuration (the separation guard fails the build).",
            "Every source file starts with the two-line SPDX header used in the existing files.",
            "Modules take their dependencies as arguments (`db`, `fetch`, `now`, `config`); see `core/README.md`.",
            "Specifications live in `ultrastable/spec`. Change a status label there in the same piece of work as the code that makes it true.",
        ],
    },
    "spec": {
        "what": "The architectural specifications (`US-SPEC-*`), scope, and documentation.",
        "test": "`python tools/spec_truth.py --spec-dir specs --code-dir <workers checkout> --code-dir .` (no false BUILT), and the link check in CI.",
        "rules": [
            "Normative text uses MUST, SHOULD, MAY with stable requirement ids. Never renumber an id.",
            "Status labels are BUILT, RUNNING or PLANNED and nothing else. BUILT names a file and a passing test in `ultrastable/workers`.",
            "`SCOPE.md` is the scope boundary. Public text must agree with it and must not promise platforms other than Cloudflare Workers.",
        ],
    },
    "license": {
        "what": "The Ultrastable License, the commercial terms and the FAQ.",
        "test": "`node scripts/check-copies.mjs workers spec` (the license files in every repository must be identical).",
        "rules": [
            "The license text is immutable once released: a change is a new version, never an edit.",
            "Pricing numbers live in `COMMERCIAL-TERMS.md` only. Every change is a protected change with a human reviewer.",
            "Not legal advice: nothing here has had a lawyer's review until the repository says so.",
        ],
    },
    ".github": {
        "what": "The organization profile and community health defaults.",
        "test": "Read the rendered profile; it must agree with `SCOPE.md` in `ultrastable/spec`.",
        "rules": [
            "The profile is public. It must not promise business plans, patents, marketing or platforms other than Cloudflare Workers.",
            "Every change to the profile is a protected change.",
        ],
    },
}

SCOPE_LINE = "Scope: see `SCOPE.md` in `ultrastable/spec`. Ultrastable manages building a working system from what a person wants, on Cloudflare Workers. By default it does not write business plans, file patents, give legal or financial advice, or run marketing."


def contract_text() -> str:
    t = (HERE / "agents" / "CONTRACT.md").read_text(encoding="utf-8")
    return re.sub(r"^(<!--.*?-->\s*)+", "", t, flags=re.S).strip() + "\n"


def agents_md(repo: str) -> str:
    r = REPOS[repo]
    rules = "\n".join(f"- {x}" for x in r["rules"])
    return (f"{HDR}\n# AGENTS.md: ultrastable/{repo}\n\n{r['what']}\n\n{SCOPE_LINE}\n\n"
            f"## Work here the way Ultrastable works\n\n{contract_text()}\n"
            f"## This repository\n\n- Test: {r['test']}\n{rules}\n"
            f"- The product's own agent protocol for the organizations it creates is in `agents/AGENTS.md` (in `ultrastable/workers`); this contract is how *this* repository is run.\n")


def files(repo: str) -> dict[str, str]:
    body = agents_md(repo)
    pointer = f"{HDR}\n@AGENTS.md\n"
    cursor = (f"---\ndescription: Work in this repository under the Ultrastable self-hosting contract\nalwaysApply: true\n---\n{body}")
    pr = (f"{HDR}\n## What\n\n<!-- one or two sentences -->\n\n"
          "Item: <#issue this work belongs to>\n"
          "Spec: <requirement ids, e.g. US-08-R03, or n/a with a reason>\n"
          "Prediction: <metric> <op> <number> within <N> h   (or: n/a, <reason>)\n"
          "Evidence: <real output: the test summary line with numbers>\n"
          "Author: <tool and model, or person>\n"
          "Reviewer: <a different agent, model or person>\n"
          "<!-- Protected paths (agents, CI, policy, guards, SCOPE, license) also need:  Protected-change: <reason>  and the label protected-change -->\n")
    issue = (f"{HDR.replace('<!--', '#').replace(' -->', '')}name: Work item\ndescription: One piece of work an agent or person can finish cold\nlabels: [item]\nbody:\n"
             "  - type: textarea\n    id: problem\n    attributes: {label: Problem and context, description: What is wrong or missing, and where (paths)}\n    validations: {required: true}\n"
             "  - type: textarea\n    id: done\n    attributes: {label: Done check, description: How a different worker can tell it is done}\n    validations: {required: true}\n"
             "  - type: input\n    id: probe\n    attributes: {label: Closing probe, description: A command or check that proves it, for example npm test}\n    validations: {required: true}\n"
             "  - type: dropdown\n    id: role\n    attributes: {label: Owner role, options: [portfolio-manager, project-manager, product-manager, staff, reviewer, operations]}\n    validations: {required: true}\n"
             "  - type: input\n    id: spec\n    attributes: {label: Specification requirement ids, description: Example US-08-R03 or n/a}\n"
             "  - type: dropdown\n    id: size\n    attributes: {label: Size, options: [S, M, L]}\n")
    return {
        "AGENTS.md": body,
        "CLAUDE.md": pointer,
        "GEMINI.md": pointer,
        ".github/copilot-instructions.md": body,
        ".cursor/rules/ultrastable.mdc": cursor,
        ".github/pull_request_template.md": pr,
        ".github/ISSUE_TEMPLATE/work-item.yml": issue,
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--repo", required=True, choices=sorted(REPOS))
    ap.add_argument("--target", type=Path, required=True)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    bad = 0
    for rel, text in files(a.repo).items():
        p = a.target / rel
        have = p.read_text(encoding="utf-8").replace("\r\n", "\n") if p.exists() else None
        if a.check:
            if have != text:
                print(f"DIFFERS {rel}", file=sys.stderr)
                bad += 1
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8", newline="\n")
            print(f"{'wrote' if have != text else 'same '} {rel}")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
