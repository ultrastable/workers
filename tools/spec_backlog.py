"""Turn the specifications' implementation-status sections into a backlog.

Every capability a specification does not label BUILT becomes one work item: PLANNED ones are built, and
ones that only RUN in the reference fleet (no code here) are generalized. `remaining` (PLANNED + running-only)
is the self-hosted organization's north-star metric: it should only fall, each fall a reviewed pull request.

  python tools/spec_backlog.py --spec-dir ../ultrastable-spec/specs --summary
  python tools/spec_backlog.py --spec-dir ../ultrastable-spec/specs --sql > seed-backlog.sql

Stdlib only. Reads files; writes nothing unless you redirect stdout.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

LABEL = re.compile(r"\b(BUILT|RUNNING|PLANNED|NOT COVERED)\b")
HEADING = re.compile(r"^#{2,3}\s+.*implementation status", re.I)


def _rows(section: list[str]):
    """Yield (capability, status_text) from table rows and bullet lines of a status section."""
    for line in section:
        t = line.strip()
        if t.startswith("|"):
            cells = [c.strip() for c in t.strip("|").split("|")]
            if len(cells) >= 2 and not set(cells[0]) <= set("-: ") and cells[0].lower() not in ("capability", "area", "item"):
                yield cells[0], " ".join(cells[1:])
        elif t.startswith(("- ", "* ")):
            body = t[2:]
            head, _, rest = body.partition(":")
            yield (head if rest else body[:100]), (rest or body)


def parse_spec(path: Path) -> list[dict]:
    text = path.read_text(encoding="utf8").splitlines()
    m = re.search(r"US-SPEC-(\d+)", path.name)
    num = int(m.group(1)) if m else 0
    out, inside = [], False
    for line in text:
        if HEADING.match(line):
            inside = True
            section: list[str] = []
            continue
        if inside and re.match(r"^##\s", line):
            inside = False
        if inside:
            section.append(line)
    if "section" not in locals():
        return out
    for k, (cap, status) in enumerate(_rows(section), 1):
        labels = LABEL.findall(status)
        if not labels:
            continue
        label = labels[0]
        if label == "RUNNING":  # running in production somewhere, but no code of ours: BUILT here is what counts
            label = "BUILT" if "BUILT" in labels else "RUNNING_ONLY"
        out.append({"spec": f"US-SPEC-{num:02d}", "n": k, "capability": re.sub(r"[`*]", "", cap).strip()[:140], "label": label})
    return out


def collect(spec_dir: Path) -> list[dict]:
    rows: list[dict] = []
    for p in sorted(spec_dir.glob("US-SPEC-*.md")):
        rows.extend(parse_spec(p))
    return rows


def summary(rows: list[dict]) -> dict:
    counts = {"BUILT": 0, "RUNNING_ONLY": 0, "PLANNED": 0, "NOT COVERED": 0}
    for r in rows:
        counts[r["label"]] += 1
    total = sum(counts.values())
    remaining = counts["PLANNED"] + counts["RUNNING_ONLY"] + counts["NOT COVERED"]
    return {**counts, "total": total, "remaining": remaining, "built_share": round(counts["BUILT"] / (total or 1), 3)}


def items(rows: list[dict]) -> list[dict]:
    out = []
    for r in rows:
        if r["label"] == "BUILT":
            continue
        num = int(r["spec"].split("-")[-1])
        verb = {"PLANNED": "Build", "RUNNING_ONLY": "Generalize (runs elsewhere, no code here)"}.get(r["label"], "Cover")
        out.append({
            "id": f"{r['spec']}-{r['n']}", "title": f"{verb}: {r['capability']} ({r['spec']})", "kind": "work", "project": "spec-to-code",
            "owner_role": "staff", "priority": 30 + num,
            "done_check": f"{r['spec']} status row for this capability reads BUILT, names the file, and the tests it names pass",
            "closing_probe": "manual",
        })
    return out


def sql(its: list[dict]) -> str:
    q = lambda v: "NULL" if v is None else "'" + str(v).replace("'", "''") + "'"
    lines = ["-- generated by tools/spec_backlog.py; idempotent"]
    for i in its:
        lines.append(
            "INSERT OR IGNORE INTO items (id, title, kind, project, owner_role, done_check, closing_probe, priority, status) VALUES "
            f"({q(i['id'])}, {q(i['title'])}, {q(i['kind'])}, {q(i['project'])}, {q(i['owner_role'])}, {q(i['done_check'])}, {q(i['closing_probe'])}, {i['priority']}, 'open');")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--spec-dir", type=Path, required=True)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--summary", action="store_true")
    g.add_argument("--json", action="store_true")
    g.add_argument("--sql", action="store_true")
    a = ap.parse_args(argv)
    rows = collect(a.spec_dir)
    if not rows:
        print("no status rows found; is --spec-dir the specs directory?", file=sys.stderr)
        return 2
    if a.sql:
        sys.stdout.write(sql(items(rows)))
    elif a.json:
        print(json.dumps(items(rows), indent=2))
    else:
        print(json.dumps(summary(rows), indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
