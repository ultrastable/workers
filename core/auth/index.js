// OWNER-AUTH-1: who is the owner is read from the repository, never typed. The person signs in with GitHub (one click, through the
// installed GitHub App); GitHub reports their permission on the repository the organization was started from; that permission decides
// the role. No console key, no hard-coded email, no token. Pure functions: the Worker supplies the GitHub answers and a session key.
const enc = new TextEncoder();
const b64u = b => btoa(String.fromCharCode(...b)).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
const unb64u = s => Uint8Array.from(atob(String(s).replace(/-/g, '+').replace(/_/g, '/')), c => c.charCodeAt(0));

/** viewer (read-only, the public view) | owner (write and execute). GitHub's repository permission 'admin' (or an org owner) is the owner. */
export function roleFor({ permission, orgRole } = {}) {
  return permission === 'admin' || orgRole === 'admin' ? 'owner' : 'viewer';
}

/** The address a step-up code goes to: the user's primary verified GitHub email, read at send time, never stored in configuration. */
export function pickVerifiedEmail(emails) {
  const ok = (Array.isArray(emails) ? emails : []).filter(e => e && e.verified && typeof e.email === 'string' && !/noreply\.github\.com$/i.test(e.email));
  return (ok.find(e => e.primary) || ok[0])?.email || null;
}

/** a***@example.com: what the screen shows, so nobody has to type or remember the address. */
export function maskEmail(email) {
  const m = String(email || '').match(/^(.)[^@]*(@.+)$/);
  return m ? m[1] + '***' + m[2] : '';
}

async function hmac(key, data) {
  const k = await crypto.subtle.importKey('raw', enc.encode(key), { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']);
  return b64u(new Uint8Array(await crypto.subtle.sign('HMAC', k, enc.encode(data))));
}

/** A signed, expiring session: { login, role, exp }. The key is generated by the Worker and kept in its vault; nobody sets it. */
export async function issueSession({ login, role, key, now = Date.now(), ttlMs = 8 * 3600e3 }) {
  if (!key || !login) throw new Error('auth: a session needs a key and a login');
  const body = b64u(enc.encode(JSON.stringify({ login, role: role === 'owner' ? 'owner' : 'viewer', exp: now + ttlMs })));
  return body + '.' + await hmac(key, body);
}

/** The session, or null when it is forged, expired or malformed. A missing key never authenticates anyone. */
export async function readSession(token, { key, now = Date.now() }) {
  const [body, sig] = String(token || '').split('.');
  if (!key || !body || !sig) return null;
  const want = await hmac(key, body);
  if (want.length !== sig.length || [...want].reduce((d, c, i) => d | (c.charCodeAt(0) ^ sig.charCodeAt(i)), 0) !== 0) return null;
  try { const s = JSON.parse(new TextDecoder().decode(unb64u(body))); return s.exp > now ? s : null; } catch { return null; }
}

/** Write and execute operations need an owner session; everything else is the public read-only view. */
export const canWrite = session => session?.role === 'owner';
