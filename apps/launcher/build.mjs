// Build the preview Worker that Door A deploys: bundle preview/entry.js, hash it, collect the migrations, and write
// src/bundle.generated.js (or another file with --out). The launcher shows the hash; CI publishes the same bytes.
// Usage: node apps/launcher/build.mjs [--out <file>]
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const out = argv.includes('--out') ? path.resolve(argv[argv.indexOf('--out') + 1]) : path.join(HERE, 'src', 'bundle.generated.js');
const outdir = mkdtempSync(path.join(tmpdir(), 'us-preview-'));
const npx = process.platform === 'win32' ? 'npx.cmd' : 'npx';
const r = spawnSync(npx, ['wrangler', 'deploy', '--dry-run', '--outdir', outdir], { cwd: path.join(HERE, 'preview'), encoding: 'utf8', shell: process.platform === 'win32' });
if (r.status !== 0) { console.error(r.stdout + r.stderr); console.error('bundle build failed'); process.exit(1); }
const bundle = readFileSync(path.join(outdir, 'entry.js'), 'utf8');
const sha = createHash('sha256').update(bundle).digest('hex');
const migDir = path.join(HERE, '..', '..', 'core', 'migrations');
const migrations = readdirSync(migDir).filter(n => n.endsWith('.sql')).sort().map(n => readFileSync(path.join(migDir, n), 'utf8')).join('\n');
const compat = JSON.parse(readFileSync(path.join(HERE, 'preview', 'wrangler.jsonc'), 'utf8')).compatibility_date;
const text = `// SPDX-License-Identifier: LicenseRef-Ultrastable-USL-1.0\n// Copyright (c) 2026 Rowan Brad Quni-Gudzinas. Non-commercial use free; commercial use requires a license. See LICENSE.\n// GENERATED by apps/launcher/build.mjs. Do not edit.\nexport const BUNDLE = ${JSON.stringify(bundle)};\nexport const BUNDLE_SHA256 = ${JSON.stringify(sha)};\nexport const MIGRATIONS_SQL = ${JSON.stringify(migrations)};\nexport const COMPATIBILITY_DATE = ${JSON.stringify(compat)};\n`;
writeFileSync(out, text);
console.log(JSON.stringify({ out, bytes: bundle.length, sha256: sha, migrations: migrations.length }));
